// Research well-known UI/product designers with Fiber AI and save public profile fields
// (name, role, company, headline, location, LinkedIn) to vault/Designers/fiber-designers.json.
// Never requests emails or phone numbers. Run: npm run fiber
import { healthCheck, getOrgCredits, slushieRun } from '@fiberai/sdk';
import { mkdir, writeFile } from 'node:fs/promises';

const apiKey = process.env.FIBER_API_KEY;
if (!apiKey && !process.argv.includes('--render')) { console.error('Set FIBER_API_KEY in .env.local first.'); process.exit(1); }
const PAGE = Number(process.env.FIBER_PAGE_SIZE || 12);
const queries = [
  ['product-leads', 'Heads of design, design directors and principal product designers at Linear, Vercel, Stripe, Figma, Airbnb, Apple and Arc (The Browser Company)'],
  ['design-engineers', 'Design engineers known for interaction design, motion and UI craft at developer tool startups in San Francisco and New York'],
  ['studios', 'Founders and creative directors of independent digital product design studios in Europe'],
  ['type-brand', 'Typeface designers and brand identity designers who also design websites and apps'],
  ['mobile', 'Senior mobile app UI designers at consumer apps known for great design such as Duolingo, Headspace, Revolut, Monzo and Spotify'],
];

import { readFile } from 'node:fs/promises';
const jsonUrl = new URL('../vault/Designers/fiber-designers.json', import.meta.url);
const render = process.argv.includes('--render');
let results = {}, charges = [], raw = {};
if (render) ({ results, charges } = JSON.parse(await readFile(jsonUrl, 'utf8')));
else {
const health = await healthCheck();
console.log('healthCheck:', health.response?.status, JSON.stringify(health.data));
const credits = await getOrgCredits({ query: { apiKey } });
const c = credits.data?.output?.[0];
console.log('credits available:', c?.available, 'of', c?.max, '(used', c?.used + ')');
const estimate = queries.length * (2 + PAGE);
if (c && c.available < estimate) { console.error('Not enough credits for about ' + estimate + '; lower FIBER_PAGE_SIZE.'); process.exit(1); }
if (process.argv.includes('--check')) process.exit(0);

const pick = p => {
  const job = p.currentJob || p.current_job || (p.experiences || p.workExperience || [])[0] || {};
  return {
    name: p.name || p.full_name || p.fullName || [p.firstName || p.first_name, p.lastName || p.last_name].filter(Boolean).join(' '),
    headline: p.headline || '',
    title: job.title || p.title || '',
    company: job.companyName || job.company_name || job.company?.name || p.companyName || '',
    location: p.locality || p.location || [p.city, p.country].filter(Boolean).join(', '),
    linkedin: p.url || p.linkedinUrl || p.linkedin_url || (p.slug ? 'https://www.linkedin.com/in/' + p.slug : ''),
    skills: (p.skills || []).slice(0, 8).map(s => typeof s === 'string' ? s : s.name).filter(Boolean),
    summary: String(p.summary || p.about || '').slice(0, 400),
  };
};

for (const [key, query] of queries) {
  const r = await slushieRun({ body: { apiKey, query, pageSize: PAGE } });
  if (r.error) { console.error(key, 'failed:', JSON.stringify(r.error).slice(0, 300)); continue; }
  const out = r.data?.output || r.data || {};
  raw[key] = r.data;
  // The result list sits at different depths depending on result type; take the largest array of objects with a name.
  const arrays = [];
  (function find(n, d) { if (!n || typeof n !== 'object' || d > 5) return; if (Array.isArray(n)) { if (n.some(x => x && typeof x === 'object')) arrays.push(n); n.forEach(x => find(x, d + 1)); return; } Object.values(n).forEach(v => find(v, d + 1)); })(out, 0);
  const people = arrays.filter(a => a.some(x => x && (x.name || x.full_name || x.fullName || x.first_name || x.firstName))).sort((a, b) => b.length - a.length)[0] || [];
  results[key] = { query, people: people.map(pick).filter(p => p.name) };
  charges.push({ key, chargeInfo: r.data?.chargeInfo || out.chargeInfo || null });
  console.log(key + ': ' + results[key].people.length + ' people', JSON.stringify(r.data?.chargeInfo || out.chargeInfo || ''));
  if (!results[key].people.length) console.log('  response keys:', Object.keys(out).join(', '));
}
}
if (!render && process.env.FIBER_RAW) await writeFile(process.env.FIBER_RAW, JSON.stringify(raw, null, 1));
await mkdir(new URL('../vault/Designers/', import.meta.url), { recursive: true });
if (!render) await writeFile(jsonUrl, JSON.stringify({ fetched: new Date().toISOString(), source: 'Fiber AI slushieRun (natural-language people search)', results, charges }, null, 2) + '\n');
console.log('Saved vault/Designers/fiber-designers.json');
const esc = v => String(v || '').replace(/\|/g, '/').replace(/\n/g, ' ');
const md = ['---', 'tags: [designers, fiber]', '---', '# Fiber results', '', 'Generated by `npm run fiber` on ' + new Date().toISOString().slice(0, 10) + ' from Fiber AI natural-language people search. Public professional fields only. These real people inspired the anonymous [[Profiles]]; see [[Designers]].', ''];
for (const [key, { query, people }] of Object.entries(results)) {
  const isDesign = p => /design|designer|\bux\b|\bui\b|creative|brand|typeface|type designer|art direct/i.test(p.title + ' ' + p.headline) && !/manufactur|battery|recruit|career/i.test(p.title + ' ' + p.headline);
  const link = u => /^https?:/.test(u) ? u : 'https://www.' + String(u).replace(/^www\./, '');
  const row = p => '| ' + (p.linkedin ? '[' + esc(p.name) + '](' + link(p.linkedin) + ')' : esc(p.name)) + ' | ' + esc(p.title) + ' | ' + esc(p.company) + ' | ' + esc(p.location) + ' | ' + esc(p.headline).slice(0, 120) + ' |';
  const head = ['| Name | Role | Company | Location | Headline |', '|---|---|---|---|---|'];
  md.push('## ' + key, '', '> ' + query, '');
  if (!people.length) { md.push('No matches for this query.', ''); continue; }
  md.push(...head, ...people.filter(isDesign).map(row), '');
  const other = people.filter(p => !isDesign(p));
  if (other.length) md.push('Other matches (not clearly design roles):', '', ...head, ...other.map(row), '');
  continue;
  for (const p of people) md.push('| ' + (p.linkedin ? '[' + esc(p.name) + '](' + p.linkedin + ')' : esc(p.name)) + ' | ' + esc(p.title) + ' | ' + esc(p.company) + ' | ' + esc(p.location) + ' | ' + esc(p.headline).slice(0, 120) + ' |');
  md.push('');
}
await writeFile(new URL('../vault/Designers/Fiber results.md', import.meta.url), md.join('\n'));
console.log('Saved vault/Designers/Fiber results.md');
